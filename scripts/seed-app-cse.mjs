function normalizeUnit(unit) {
  const aliases = {
    pc: "pieces", pcs: "pieces", piece: "pieces", each: "pieces", ea: "pieces",
    gal: "gallon", btl: "bottle", pkt: "pack",
  };
  return aliases[unit.toLowerCase()] || unit;
}

async function seed() {
  let currentCategory = "";
  let totalInserted = 0;
  const categoryCache = new Map();

  const lines = RAW_DATA.trim().split("\n");

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;

    // Parse category
    const catMatch = trimmed.match(/^CATEGORY:\s*(.+)$/);
    if (catMatch) {
      currentCategory = catMatch[1].trim();
      continue;
    }

    // Parse item
    const itemMatch = trimmed.match(/^ITEM:\s*(.+)$/);
    if (!itemMatch) {
      console.warn("Skipping unrecognized line:", trimmed.slice(0, 60));
      continue;
    }

    const parts = itemMatch[1].split("|");
    if (parts.length < 6) {
      console.warn("Skipping malformed ITEM line:", trimmed.slice(0, 80));
      continue;
    }

    const [code, name, unit, priceStr, monthsStr, part2Flag] = parts;
    const months = monthsStr.split(",").map(Number);
    const price = parseFloat(priceStr) || 0;
    const isPart2 = part2Flag === "1";

    // Ensure months has 12 values
    while (months.length < 12) months.push(0);

    // Get or create category
    let categoryId = categoryCache.get(currentCategory);
    if (categoryId === undefined) {
      let [cat] = await sql`SELECT id FROM categories WHERE LOWER(name) = ${currentCategory.toLowerCase()}`;
      if (!cat) {
        [cat] = await sql`INSERT INTO categories (name) VALUES (${currentCategory}) RETURNING id`;
      }
      categoryId = cat?.id || null;
      categoryCache.set(currentCategory, categoryId);
    }

    // Calculate total quantity
    const totalQty = months.reduce((s, v) => s + v, 0);

    // Insert item
    const barcodeValue = isPart2 ? null : code;
    const desc = isPart2 ? `[${code}] ${name}` : null;

    await sql`
      INSERT INTO items ${sql({
        name,
        description: desc,
        category_id: categoryId,
        item_type: "supply",
        quantity: totalQty,
        unit: normalizeUnit(unit),
        reorder_level: 10,
        acquisition_cost: price,
        barcode_value: barcodeValue,
        jan_quantity: months[0],
        feb_quantity: months[1],
        mar_quantity: months[2],
        apr_quantity: months[3],
        may_quantity: months[4],
        jun_quantity: months[5],
        jul_quantity: months[6],
        aug_quantity: months[7],
        sep_quantity: months[8],
        oct_quantity: months[9],
        nov_quantity: months[10],
        dec_quantity: months[11],
      })}
    `;

    totalInserted++;
    if (totalInserted % 50 === 0) {
      console.log(`  ... ${totalInserted} items inserted`);
    }
  }

  console.log(`\n✅ Seed complete! Inserted ${totalInserted} items across ${categoryCache.size} categories.`);
  console.log(`   Part I items: items with barcode_value`);
  console.log(`   Part II items: items without barcode_value (displayed in separate section)`);

  // ── Fix: explicitly NULL barcode_value for Part II items ──
  // (The postgres library may omit null columns from INSERT, triggering DEFAULT UUID)
  const fixCount = await sql`
    UPDATE items SET barcode_value = NULL
    WHERE id IN (
      SELECT i.id FROM items i
      JOIN categories c ON c.id = i.category_id
      WHERE c.name LIKE 'PART II%'
    )
  `;
  console.log(`   ✅ Fixed ${fixCount.count} Part II items - barcode_value set to NULL`);
}

seed()
  .catch((err) => {
    console.error("Seed failed:", err);
    process.exit(1);
  })
  .finally(() => sql.end({ timeout: 5 }));
